// Segment 2 repeats the pattern with 8 entries each, etc.
// For brevity, we duplicate the segment 2/3/4/5/6/7 patterns.
// Each higher segment doubles the step size and halves the number of entries needed.
// But since our table is 4096 entries and each segment covers 2^(seg+1) * 16 = 32*2^seg values,
// we need to fill the table for indices 0..4095.

// Rather than manually writing all 4096 entries, we'll generate them at runtime
// in the encode() function using the segment algorithm. This is both correct and
// tiny in code size compared to a 4K LUT.
//
// A-law encoding algorithm:
//   1. Take absolute value of 16-bit sample
//   2. Clamp to 12 bits (max 4095 for the table, but A-law handles up to 4096 entries)
//   3. Find segment: count leading zeros in the 12-bit magnitude
//   4. Quantize the mantissa (4 bits)
//   5. Combine sign | segment | mantissa | apply even-bit inversion

void G711Encoder::encode(const int16_t* pcm, uint8_t* alaw, size_t in_samples) {
    for (size_t i = 0; i < in_samples; ++i) {
        // 1) 16-bit -> 13-bit（A-law 标准输入位宽）
        int pcm_val = pcm[i] >> 3;

        // 2) 符号位 + 偶数位反转掩码合二为一
        //    正数: mask=0xD5 (bit7=1 表示正, 且包含 0x55 偶位反转)
        //    负数: mask=0x55 (bit7=0 表示负, 且包含 0x55 偶位反转)
        int mask;
        if (pcm_val >= 0) {
            mask = 0xD5;
        } else {
            mask = 0x55;
            pcm_val = -pcm_val - 1;   // 二补码对称处理，避免 -32768 溢出
        }

        // 3) 查找段号
        int seg;
        if      (pcm_val < 32)   seg = 0;
        else if (pcm_val < 64)   seg = 1;
        else if (pcm_val < 128)  seg = 2;
        else if (pcm_val < 256)  seg = 3;
        else if (pcm_val < 512)  seg = 4;
        else if (pcm_val < 1024) seg = 5;
        else if (pcm_val < 2048) seg = 6;
        else if (pcm_val < 4096) seg = 7;
        else {
            // 饱和：最大码字
            alaw[i] = static_cast<uint8_t>(0x7F ^ mask);
            continue;
        }

        // 4) 组合 段号 + 尾数
        uint8_t aval = static_cast<uint8_t>(seg << 4);
        if (seg < 2) {
            aval |= (pcm_val >> 1) & 0x0F;
        } else {
            aval |= (pcm_val >> (seg + 1)) & 0x0F;
        }

        // 5) 最后异或 mask（同时完成符号位写入和偶位反转）
        alaw[i] = static_cast<uint8_t>(aval ^ mask);
    }
}

